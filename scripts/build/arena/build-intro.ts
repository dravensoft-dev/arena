/* Bundles each intro/ page's module entry, so those pages may reach into scripts/ without
 * the browser having to. Before this the two modules overview.js imports had to stay
 * JavaScript, because a browser runs what the git tag serves and nothing built it.
 * The entries are read out of the pages rather than listed here: a page names its own
 * `<script type="module">`, and that name is the generated one, so a page added tomorrow
 * is covered the day it lands. The output is TRACKED for the reason .gitignore already
 * gives the design tokens -- the Claude Code plugin is served from the tag, where no build
 * runs -- and check:intro is what keeps a tracked bundle honest. moduleEntries() requires
 * the generated suffix rather than deriving it: a page pointing straight at its source
 * would be served source, which is the arrangement this script exists to end. */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { isMainModule } from '../../utils/main-module.ts';
import { repoRoot } from '../../lib/arena/repo-root.ts';
import { captured } from '../../utils/captures.ts';

export const PAGE_DIR = 'intro';
export const GENERATED_SUFFIX = '.generated.js';

export const node = {
  name: 'build:intro',
  reads: [`${PAGE_DIR}/*.html`, `${PAGE_DIR}/*.js`, `!${PAGE_DIR}/*${GENERATED_SUFFIX}`],
  writes: [`${PAGE_DIR}/*${GENERATED_SUFFIX}`],
  feeds: [
    'check:generated',
    'check:icons',
    'check:intro',
    'build:site',
  ],
};

const MODULE_ENTRY = /<script[^>]*\stype="module"[^>]*\ssrc="([^"]+)"/g;

export const BANNER = (source: string) =>
  `/* GENERATED by scripts/build/arena/build-intro.ts from ${source} — edit that, not this.\n`
  + ' * A browser bundle: the page loads this, so what it imports out of scripts/ never\n'
  + ' * has to be servable on its own. See build-intro.ts for why the tag needs it tracked. */\n';

export function pages(root = repoRoot): string[] {
  return readdirSync(join(root, PAGE_DIR))
    .filter((name) => name.endsWith('.html'))
    .sort();
}

export function moduleEntries(root = repoRoot) {
  const found = [];
  for (const page of pages(root)) {
    const html = readFileSync(join(root, PAGE_DIR, page), 'utf8');
    for (const m of html.matchAll(MODULE_ENTRY)) {
      const out = captured(m).replace(/^\.\//, '');
      if (!out.endsWith(GENERATED_SUFFIX)) {
        throw new Error(
          `build-intro: ${PAGE_DIR}/${page} loads "${m[1]}" as a module, and a module entry must be `
          + `a ${GENERATED_SUFFIX} bundle. A page that loads its source directly serves whatever that `
          + 'source imports, which is what put two scripts/ modules out of reach of TypeScript.',
        );
      }
      found.push({ page, out, source: `${out.slice(0, -GENERATED_SUFFIX.length)}.js` });
    }
  }
  return found;
}

export async function buildIntro(opts: { root?: string } = {}) {
  const root = opts.root ?? repoRoot;
  const built = new Map<string, string>();

  for (const { out, source } of moduleEntries(root)) {
    const result = await Bun.build({
      entrypoints: [join(root, PAGE_DIR, source)],
      format: 'esm',
      target: 'browser',
    });
    if (!result.success) {
      const messages = result.logs.map((l) => l.message).join('\n');
      throw new Error(`build-intro: ${PAGE_DIR}/${source} failed to bundle\n${messages}`);
    }
    const [bundled] = result.outputs;
    if (!bundled) throw new Error(`build-intro: Bun.build produced no output for ${source}`);
    built.set(out, BANNER(`${PAGE_DIR}/${source}`) + await bundled.text());
  }

  if (built.size === 0) {
    throw new Error('build-intro: no page declares a module entry, so this wrote nothing and reported success');
  }
  return built;
}

async function main() {
  const built = await buildIntro();
  for (const [out, code] of built) {
    writeFileSync(join(repoRoot, PAGE_DIR, out), code);
    console.log(`wrote ${PAGE_DIR}/${out}`);
  }
  console.log(`build-intro: ${built.size} page bundle(s)`);
}

if (isMainModule(import.meta.url)) await main();
