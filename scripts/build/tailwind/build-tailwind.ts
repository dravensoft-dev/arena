type BuildOptions = { root?: string; manifests?: Map<string, any> };

export const BANNER = '/* GENERATED by scripts/build/tailwind/build-tailwind.ts — edit frameworks/tailwind/Theme.css or a manifest, not this file. */\n';

export function manifestBanner(jsonFile: string) {
  return `/* GENERATED by scripts/build/tailwind/build-tailwind.ts — edit ${jsonFile}, not this file. */\n`;
}

export function generatedPath(opts: BuildOptions = {}) {
  return join(opts.root ?? repoRoot, 'frameworks', 'tailwind', 'Utilities.generated.css');
}

export function buildTailwind(opts: BuildOptions = {}) {
  const { css } = compileLayer(opts);
  return BANNER + css;
}

export function manifestModule(manifest: ComponentManifest, jsonFile: string) {
  const { compoundVariants, ...rest } = manifest;
  if (!compoundVariants) {
    return `${manifestBanner(jsonFile)}export default ${JSON.stringify(manifest, null, 2)} as const;\n`;
  }
  const entries = compoundVariants.map((entry) => `${JSON.stringify(entry, null, 2)} as const`).join(',\n');
  return `${manifestBanner(jsonFile)}const compoundVariants = [\n${entries},\n];\n\n`
    + `export default { ...(${JSON.stringify(rest, null, 2)} as const), compoundVariants };\n`;
}

