/* Writes frameworks/react/vendor/*.generated.js, the bare specifiers a demo page's importmap
 * resolves. React 18 is CommonJS-only, so this bundles it to ESM, appending named exports Bun's
 * static detection misses and keeping `react` external so it stays a singleton: Bun sees only
 * the `exports.x = y` assignments at the CJS wrapper's top level, and React's sit inside an
 * IIFE, so the raw output is `export default` and nothing else. Nothing else needs vendoring:
 * a component composes its own class names, so no recipe library reaches a demo page. */

import { writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { repoRoot } from '../../lib/arena/repo-root.ts';

const req = createRequire(import.meta.url);

export const BANNER =
  '/* GENERATED by scripts/build/react/build-vendor.ts — edit that, not this.\n'
  + ' * A CommonJS->ESM bundle of React 18, which ships no ESM build of its own,\n'
  + ' * for the demo pages\' <script type="importmap">. NODE_ENV is baked in as\n'
  + ' * "development". See build-vendor.ts for the full rationale. */\n';

export const RECIPE_BANNER =
  '/* GENERATED by scripts/build/react/build-vendor.ts — edit that, not this.\n'
  + ' * A browser bundle of the recipe runtime both layers render from, for the\n'
  + ' * demo pages\' <script type="importmap">. It ships ESM already, so nothing\n'
  + ' * here patches its exports. See build-vendor.ts for the full rationale. */\n';

export const ENTRIES = [
  { entry: 'react/index.js', specifier: 'react', out: 'React.generated.js', real: 'react', external: [] },
  { entry: 'react/jsx-runtime.js', specifier: 'react/jsx-runtime', out: 'ReactJsxRuntime.generated.js', real: 'react/jsx-runtime.js', external: ['react'] },
  { entry: 'react-dom/client.js', specifier: 'react-dom/client', out: 'ReactDomClient.generated.js', real: 'react-dom/client.js', external: ['react'] },
];

export const VENDOR_DIR = 'frameworks/react/vendor';

export const node = {
  name: 'build:vendor',
  reads: ['package.json', 'bun.lock'],
  writes: ENTRIES.map((entry) => `${VENDOR_DIR}/${entry.out}`),
  feeds: [
    'build:react-package',
    'check:dimensions',
    'check:duplicate-constants',
    'check:focus-trap',
    'check:generated',
    'check:pixel-parity',
    'check:layer-independence',
    'check:script-tokens',
    'check:skills',
    'check:vendor',
    'build:site',
  ],
};

function realExportNames(root: string, real: string) {
  return Object.keys(req(join(root, 'node_modules', real)));
}

export function withNamedExports(code: string, names: string[]) {
  return code.replace(/export default (.+);\s*$/, (_m, expr) => {
    const named = names.map((n) => `export const ${n} = __arenaDefault.${n};`).join('\n');
    return `const __arenaDefault = ${expr};\nexport default __arenaDefault;\n${named}\n`;
  });
}

export async function buildVendor(opts: { root?: string } = {}) {
  const root = opts.root ?? repoRoot;
  const files = new Map();
  for (const e of ENTRIES) {
    const result = await Bun.build({
      entrypoints: [join(root, 'node_modules', e.entry)],
      format: 'esm',
      target: 'browser',
      define: { 'process.env.NODE_ENV': '"development"' },
      external: e.external,
    });
    if (!result.success) {
      const messages = result.logs.map((l) => l.message).join('\n');
      throw new Error(`build-vendor: ${e.entry} failed to bundle\n${messages}`);
    }
    const [bundled] = result.outputs;
  if (!bundled) throw new Error('build-vendor: Bun.build produced no output');
  const raw = await bundled.text();
    if (!e.real) {
      files.set(e.out, RECIPE_BANNER + raw);
      continue;
    }
    const names = realExportNames(root, e.real);
    files.set(e.out, BANNER + withNamedExports(raw, names));
  }
  return files;
}

async function main() {
  const files = await buildVendor();
  const dir = join(repoRoot, 'frameworks/react/vendor');
  mkdirSync(dir, { recursive: true });
  for (const [name, content] of files) {
    writeFileSync(join(dir, name), content);
    console.log(`wrote frameworks/react/vendor/${name}`);
  }
}

if (import.meta.main) await main();
