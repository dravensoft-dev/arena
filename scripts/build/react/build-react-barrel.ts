/* The React layer's entry point, one `export *` per component plus the layer-root helpers.
 * Derived from the tree rather than hand-listed, because a hand-listed barrel is how the
 * Angular layer shipped five primitives nobody could import. Tokens.generated is left out
 * for the reason its Angular counterpart is: a value bound at import time cannot re-theme
 * and cannot re-densify, and nobody types data with it. The output is git-ignored, and
 * check-react-barrel.ts holds it to a fresh run. */

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { isMainModule } from '../../utils/main-module.ts';
import { SOURCE_EXTENSIONS } from './build-demos.ts';
import { repoRoot } from '../../lib/arena/repo-root.ts';
import { pascal } from '../../utils/case.ts';
import { byKey } from '../../utils/compare.ts';

export const BANNER =
  '/* GENERATED by scripts/build/react/build-react-barrel.ts -- add a component directory, not a line here. */\n';

export const HELPERS = ['AnchorActivation', 'DataVisuals', 'UseArenaContainerWidth', 'UseDialogModal', 'UseArenaToasts', 'ToastClock', 'Theme', 'WarnOnce'];

export const TYPE_ONLY = ['Api.generated'];

export const BARREL_TARGET = 'frameworks/react/Index.generated.ts';

export const node = {
  name: 'build:react-barrel',
  reads: [
    ...[...SOURCE_EXTENSIONS, '.ts', '.js'].map((ext) => `frameworks/react/components/**/*${ext}`),
    '!frameworks/react/components/**/*.generated.*',
    ...HELPERS.map((helper) => `frameworks/react/${helper}.*`),
  ],
  writes: [BARREL_TARGET],
  feeds: [
    'build:react-package',
    'check:arbitrary',
    'check:dimensions',
    'check:duplicate-constants',
    'check:generated',
    'check:icons',
    'check:layer-independence',
    'check:react-barrel',
    'check:react-types',
    'check:script-tokens',
    'check:shared-arithmetic',
    'check:skills',
  ],
};

export const ROOT_PRIVATE = new Map([
  ['Tokens.generated', 'bare numbers a component reads to compute a position, and the one thing '
    + 'the token layer warns about: a value bound at import time cannot re-theme and cannot '
    + 're-densify. Api.generated is exported because a consumer types their own data with it; '
    + 'nobody types data with calendarHourH.'],
]);

export function sourceExtension(base: string) {
  return [...SOURCE_EXTENSIONS, '.ts', '.js'].find((e) => existsSync(`${base}${e}`)) ?? null;
}

export function componentModules(root = repoRoot) {
  const base = join(root, 'frameworks', 'react', 'components');
  const found = [];
  for (const category of readdirSync(base, { withFileTypes: true }).sort(byKey((entry) => entry.name))) {
    if (!category.isDirectory()) continue;
    const categoryDir = join(base, category.name);
    for (const dir of readdirSync(categoryDir, { withFileTypes: true }).sort(byKey((entry) => entry.name))) {
      if (!dir.isDirectory()) continue;
      const component = pascal(dir.name);
      found.push({
        component,
        path: `./components/${category.name}/${dir.name}/${component}`,
        ext: sourceExtension(join(categoryDir, dir.name, component)),
      });
    }
  }
  return found;
}

export function zeroComponentProblems(count: number) {
  if (count > 0) return [];
  return ['found 0 component directories under frameworks/react/components; an empty barrel is a failure, not a clean pass'];
}

export function missingSourceProblems(modules: ReturnType<typeof componentModules>, root = repoRoot) {
  const problems = [];
  for (const { component, path, ext } of modules) {
    const base = join(root, 'frameworks', 'react', path.slice(2));
    if (!ext) {
      problems.push(`${component}: no ${path}.jsx and no ${path}.tsx, so the barrel would export nothing`);
      continue;
    }
    if (ext === '.jsx' && !existsSync(`${base}.d.ts`))
      problems.push(`${component}: no ${path}.d.ts beside the .jsx, so the package would ship it untyped`);
  }
  return problems;
}

export function duplicateExportProblems(modules: ReturnType<typeof componentModules>, root = repoRoot) {
  const seen = new Map();
  const problems = [];
  for (const { component, path, ext } of modules) {
    if (!ext) continue;
    const source = readFileSync(join(root, 'frameworks', 'react', `${path.slice(2)}${ext}`), 'utf8');
    for (const match of source.matchAll(/^export\s+(?:function|const|class)\s+([A-Za-z0-9_$]+)/gm)) {
      const name = match[1];
      if (seen.has(name)) {
        problems.push(`${name} is exported by both ${seen.get(name)} and ${component}; one export * would shadow the other`);
      }
      seen.set(name, component);
    }
  }
  return problems;
}

const reExport = (specifier: string) => `export * from '${specifier}';`;

export function barrel(modules: ReturnType<typeof componentModules>, root = repoRoot) {
  const lines = [
    BANNER,
    ...TYPE_ONLY.map((t) => `export type * from './${t}.ts';`),
    '',
    ...modules.map(({ path, ext }) => reExport(`${path}${ext ?? '.jsx'}`)),
    '',
    ...HELPERS.map((h) => reExport(`./${h}${sourceExtension(join(root, 'frameworks', 'react', h)) ?? '.js'}`)),
  ];
  return `${lines.join('\n')}\n`;
}

export function buildBarrel(root = repoRoot) {
  const modules = componentModules(root);
  const problems = [
    ...zeroComponentProblems(modules.length),
    ...missingSourceProblems(modules, root),
    ...duplicateExportProblems(modules, root),
  ];
  const files = new Map([
    ['frameworks/react/Index.generated.ts', barrel(modules, root)],
  ]);
  return { files, problems, count: modules.length };
}

function main() {
  const { files, problems, count } = buildBarrel();
  for (const problem of problems) console.error(`build-react-barrel: ${problem}`);
  if (problems.length) process.exit(1);

  for (const [rel, content] of files) {
    writeFileSync(join(repoRoot, rel), content);
    console.log(`build-react-barrel: wrote ${rel}`);
  }
  console.log(`build-react-barrel: ${count} component(s) and ${HELPERS.length} helper(s)`);
}

if (isMainModule(import.meta.url)) main();
