/* A demo page loads the compiled sibling, and a browser cannot execute TypeScript, so
 * every module a component reaches is compiled here: the components themselves, the demo
 * entries, and the layer-root helpers in ROOT_MODULES. One left out is a module that 404s
 * on the page with every suite still green, because a suite imports the source. */

import { readFileSync, writeFileSync } from 'node:fs';
import { basename, join, relative } from 'node:path';
import { toPosix, relPosix } from '../../utils/posix-path.ts';
import { walkFiles } from '../../utils/walk-files.ts';
import { repoRoot } from '../../lib/arena/repo-root.ts';

export const BANNER =
  '/* GENERATED by scripts/build/react/build-demos.ts — edit the source sibling, not this file.\n'
  + ' * Bun.Transpiler, classic JSX (React.createElement). See build-demos.ts\n'
  + ' * for the full rationale. */\n';

export const ROOTS = [
  'frameworks/react/components', 'frameworks/react/kitchen-sink', 'frameworks/react/playground',
];

export const ROOT_MODULES = [
  'frameworks/react/AnchorActivation.ts', 'frameworks/react/DataVisuals.ts',
  'frameworks/react/Theme.ts',
  'frameworks/react/UseArenaContainerWidth.ts', 'frameworks/react/UseDialogModal.ts',
  'frameworks/react/WarnOnce.ts', 'frameworks/react/Tv.generated.ts',
  'frameworks/react/ArenaStyles.generated.ts',
];

export const SOURCE_EXTENSIONS = ['.jsx', '.tsx'];
export const COMPILED_EXTENSIONS = ['.jsx', '.tsx', '.ts'];

export const node = {
  name: 'build:demos',
  reads: [
    ...ROOTS.flatMap((root) => COMPILED_EXTENSIONS.map((ext) => `${root}/**/*${ext}`)),
    ...ROOT_MODULES,
  ],
  writes: ROOTS.map((root) => `${root}/**/*.generated.js`),
  feeds: [
    'build:react-package',
    'check:appearance',
    'check:parts',
    'check:kitchen-sink',
    'check:pixel-parity',
    'check:behaviour',
    'check:compliance',
    'check:demos',
    'check:dimensions',
    'check:duplicate-constants',
    'check:focus-trap',
    'check:generated',
    'check:icons',
    'check:layer-independence',
    'check:playgrounds',
    'check:script-tokens',
    'check:shared-arithmetic',
    'check:skills',
    'check:states',
    'build:site',
  ],
};

export function loaderFor(path: string) {
  return path.endsWith('.tsx') || path.endsWith('.ts') ? 'tsx' : 'jsx';
}

export function findSourceFiles(dir: string) {
  return walkFiles(dir)
    .filter((path) => COMPILED_EXTENSIONS.some((e) => path.endsWith(e)))
    .filter((path) => !basename(path).includes('.test.') && !path.endsWith('.d.ts'))
    .sort();
}

export function rewriteRelativeSourceImports(code: string) {
  return code.replace(/(from\s*")(\.\.?\/[^"]+?)(?:\.generated)?\.(?:jsx|tsx|ts)"/g, '$1$2.generated.js"');
}

export function outputPathFor(relPath: string) {
  return relPath.replace(/(?:\.generated)?\.(?:jsx|tsx|ts)$/, '.generated.js');
}

export async function buildDemos(opts: { root?: string } = {}) {
  const root = opts.root ?? repoRoot;
  const tsconfig = JSON.stringify({ compilerOptions: { jsx: 'react' } });
  const transpilers = new Map(
    SOURCE_EXTENSIONS.map((e) => [loaderFor(e), new Bun.Transpiler({ loader: loaderFor(e), tsconfig })]),
  );

  const files = new Map();
  {
    const targets = [
      ...ROOTS.flatMap((treeRoot) => findSourceFiles(join(root, treeRoot))),
      ...ROOT_MODULES.map((rel) => join(root, rel)),
    ];
    for (const absPath of targets) {
      const source = readFileSync(absPath, 'utf8');
      const transpiler = transpilers.get(loaderFor(absPath));
      if (!transpiler) throw new Error(`build-demos: no transpiler is configured for ${absPath}`);
      const compiled = transpiler.transformSync(source);
      const rewritten = rewriteRelativeSourceImports(compiled);
      const outRel = toPosix(outputPathFor(relPosix(root, absPath)));
      if (files.has(outRel))
        throw new Error(`build-demos: ${outRel} is written by two sources at once; a .jsx and a .tsx `
          + 'of the same stem compile to one sibling and the second would overwrite the first');
      files.set(outRel, BANNER + rewritten);
    }
  }
  return files;
}

async function main() {
  const files = await buildDemos();
  for (const [outRel, content] of files) {
    writeFileSync(join(repoRoot, outRel), content);
    console.log(`wrote ${outRel}`);
  }
  console.log(`build-demos: ${files.size} file(s) compiled`);
}

if (import.meta.main) await main();
