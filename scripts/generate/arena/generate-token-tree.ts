export const TREE: Record<string, string[]> = {
  'index.md': ['markup/index.md', 'plugin/index.md', 'components/index.md', 'scales/index.md'],
  'markup/index.md': ['surfaces-and-text', 'edges', 'space-and-layout', 'type', 'depth-and-motion', 'layers', 'states', 'meaning-and-identity', 'units'],
  'plugin/index.md': ['surfaces-and-text', 'edges', 'space-and-layout', 'type', 'depth-and-motion', 'states'],
  'components/index.md': ['air', 'type', 'size-controls', 'size-content', 'emphasis-and-accent', 'status-hues', 'controls-and-marks'],
  'scales/index.md': ['spacing-radius-border', 'motion-and-layers', 'density', 'type-scale'],
};

const dirOf = (index: string) => index.slice(0, -'index.md'.length);
const leafPath = (index: string, child: string) => child.endsWith('index.md') ? child : `${dirOf(index)}${child}.md`;
const isScalesLeaf = (path: string) => path.startsWith('scales/') && path !== 'scales/index.md';

const leaves = Object.entries(TREE).flatMap(([index, children]) => children
  .filter((child) => !child.endsWith('index.md')).map((child) => leafPath(index, child)));

export const GENERATED_PATHS = [...Object.keys(TREE), ...leaves.filter((path) => !isScalesLeaf(path))];

const CONTROL_PARTS = new Set(['control', 'segment', 'switch', 'spinner', 'meter', 'ring']);

type Meta = { audience: string; task: string };

export function roleLeaf(name: string, meta: Meta) {
  const { audience, task } = meta;
  if (!(AUDIENCES as readonly string[]).includes(audience) || !(TASKS as readonly string[]).includes(task))
    throw new Error(`generate-token-tree: the role ${name} declares audience ${audience} and task ${task}, outside the closed sets in check-role-contract.`);
  if (audience === 'markup') return markupLeafIn(`plugin/${task}.md`, name);
  if (audience === 'component') {
    if (task === 'component-size')
      return CONTROL_PARTS.has(name.split('-')[2] ?? '') ? 'components/size-controls.md' : 'components/size-content.md';
    if (task === 'space-and-layout' || task === 'edges') return 'components/air.md';
    if (task === 'type') return 'components/type.md';
    if (task === 'depth-and-motion' || task === 'states' || /^(emphasis|accent)-/.test(name)) return 'components/emphasis-and-accent.md';
    if (task === 'meaning-and-identity') return /^hue-/.test(name) ? 'components/status-hues.md' : 'components/controls-and-marks.md';
  }
  throw new Error(`generate-token-tree: no leaf takes the role ${name} (audience ${audience}, task ${task}). `
    + 'Add the rule in roleLeaf, or the role is declared on the wrong axis.');
}

function markupLeafIn(path: string, name: string) {
  if (!leaves.includes(path)) throw new Error(`generate-token-tree: ${path} is not a leaf of the tree, so ${name} has nowhere to land.`);
  return path;
}

export function markupLeaf(task: string) {
  const path = `markup/${task}.md`;
  if (!leaves.includes(path)) throw new Error(`generate-token-tree: ${path} is not a leaf of the tree.`);
  return path;
}

type PluginTokens = Record<string, any>;

const ROLE_ALIAS = /^\{([a-z][\w-]*)\}$/;

const length = (one: any) => `${one.value}${one.unit}`;

function renderShadow(layer: any): string {
  const { offsetX, offsetY, blur, spread, color, inset } = layer;
  const flat = [offsetX, offsetY, blur, spread].every((one) => Number(one.value) === 0) && Number(color.alpha ?? 1) === 0;
  if (flat) return 'none';
  const [r = 0, g = 0, b = 0] = color.components as number[];
  const channels = [r, g, b].map((one) => Math.round(one * 255)).join(' ');
  const alpha = Number(color.alpha ?? 1);
  return `${inset === true ? 'inset ' : ''}${[offsetX, offsetY, blur, spread].map(length).join(' ')} rgb(${channels}${alpha === 1 ? '' : ` / ${alpha}`})`;
}

function renderValue(value: unknown): string {
  if (typeof value === 'object' && value !== null && 'unit' in value && 'value' in value) return `${value.value}${value.unit}`;
  if (Array.isArray(value) && value.length > 0 && value.every((one) => typeof one === 'object' && one !== null && 'offsetX' in one))
    return value.map(renderShadow).join(', ');
  if (typeof value === 'object' && value !== null && 'offsetX' in value && 'color' in value) return renderShadow(value);
  return typeof value === 'string' ? value : JSON.stringify(value);
}

function resolveAnswer(name: string, plugin: PluginTokens, roles: Record<string, RoleToken>, light: boolean, seen: string[] = []): string | undefined {
  const entry = (light ? plugin.light?.[name] : undefined) ?? plugin[name];
  if (name === 'light' || entry === undefined || !('$value' in entry)) return undefined;
  const value = entry.$value;
  const target = typeof value === 'string' ? ROLE_ALIAS.exec(value)?.[1] : undefined;
  if (target === undefined || !Object.hasOwn(roles, target) || seen.includes(target)) return renderValue(value);
  return resolveAnswer(target, plugin, roles, light, [...seen, name]) ?? renderValue(value);
}

export function defaultAnswer(name: string, plugin: PluginTokens, roles: Record<string, RoleToken>): { light: string; dark: string } | undefined {
  const dark = resolveAnswer(name, plugin, roles, false);
  const light = resolveAnswer(name, plugin, roles, true);
  return dark === undefined || light === undefined ? undefined : { light, dark };
}

const cell = (text: string) => text.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();

type Combine = { with: string; as: string };
type RoleMeta = { audience?: string; task?: string; state?: string[]; userScale?: string; default?: string; question?: string; combines?: Combine[] };
type RoleToken = { $type?: string; $description?: string; $extensions?: Record<string, RoleMeta> };

export const COMPAT: Record<'markup' | 'component', string> = {
  markup: "Your markup and Arena's components both read the roles on this page. A role keeps its name until a major release, and its value is the style plugin's to change in any release.",
  component: "Only Arena's components read the roles on this page. A role keeps its name until a major release, and its value is the style plugin's to change in any release.",
};

const THEME = 'frameworks/tailwind/Theme.css';
const NAMESPACE_PREFIX: Record<string, string> = {
  radius: 'rounded-', shadow: 'shadow-', ease: 'ease-', font: 'font-', 'font-weight': 'font-',
  text: 'text-', leading: 'leading-', tracking: 'tracking-', container: 'max-w-',
};

function colorPrefix(role: string, key: string): string[] {
  if (role === 'edge-focus') return ['ring-', 'outline-'];
  if (/^(fill|overlay)-/.test(role)) return ['bg-'];
  if (role.startsWith('ink-')) return ['text-'];
  if (role.startsWith('edge-')) return ['border-'];
  throw new Error(`generate-token-tree: the theme key --color-${key} reads the role ${role}, and no colour prefix takes a role of that name.`);
}

const SPACING_SIDE: Record<string, string> = { gutter: 'px-', 'pad-surface-head': 'pb-', 'pad-surface-head-top': 'pt-' };

function spacingPrefix(role: string) {
  if (SPACING_SIDE[role]) return SPACING_SIDE[role];
  if (role.startsWith('gap-')) return 'gap-';
  if (role.endsWith('-x')) return 'px-';
  if (role.endsWith('-y')) return 'py-';
  return 'p-';
}

const arithmeticOnly = (value: string, role: string) => {
  const stripped = value.replace(`var(--${role})`, '');
  if (stripped === value) return false;
  if (stripped.trim() === '') return true;
  return /^calc\(/.test(value.trim()) && !/[a-z]\(/.test(stripped.replace(/calc\(|var\(--[a-z0-9-]+\)/g, ''));
};

function roleThemeKeys(base: string) {
  const css = readFileSync(join(base, THEME), 'utf8');
  const decls = new Map(themeDeclarations(css));
  const namespaces = deriveNamespaces(new Map([...decls].map(([key, value]) => [key.slice(2), value])));
  const nsOf = new Map<string, [string, string]>();
  for (const [ns, keys] of namespaces as Map<string, string[]>) for (const key of keys) nsOf.set(`${ns}-${key}`, [ns, key]);
  const roles = Object.keys(readJson(join(base, ROLES)) as Record<string, unknown>);
  const out: { name: string; role: string; ns: string; key: string }[] = [];
  for (const [name, value] of decls) {
    const hit = nsOf.get(name.slice(2));
    for (const role of roles) {
      if (!arithmeticOnly(value, role)) continue;
      if (!hit) throw new Error(`generate-token-tree: the theme key ${name} reads the role ${role}, and no theme namespace places that key.`);
      out.push({ name, role, ns: hit[0], key: hit[1] });
    }
  }
  return out;
}

export function roleUtilities(base = root) {
  const out = new Map<string, string[]>();
  for (const { name, role, ns, key } of roleThemeKeys(base)) {
    const one = ns === 'color' ? colorPrefix(role, key) : [ns === 'spacing' ? spacingPrefix(role) : NAMESPACE_PREFIX[ns]];
    if (!one[0]) throw new Error(`generate-token-tree: the theme key ${name} reads the role ${role}, and the namespace ${ns} has no utility prefix here.`);
    out.set(role, [...(out.get(role) ?? []), ...one.map((prefix) => `${prefix}${key}`)]);
  }
  return out;
}

export function roleColourKeys(base = root) {
  const out = new Map<string, string[]>();
  for (const { role, ns, key } of roleThemeKeys(base)) if (ns === 'color') out.set(role, [...(out.get(role) ?? []), key]);
  return out;
}

export function combination(role: string, entry: Combine, utilities: string[]) {
  const need = (prefix: string) => {
    const found = utilities.find((utility) => utility.startsWith(prefix));
    if (!found) throw new Error(`generate-token-tree: the role ${role} combines as ${entry.as} with --${entry.with}, but no ${prefix} utility reaches it.`);
    return found;
  };
  if (entry.as === 'level') return `${need(/^(fill|overlay)-/.test(role) ? 'bg-' : 'text-')}/(--${entry.with})`;
  if (entry.as === 'width') return `${need('border-')} border-[length:var(--${entry.with})]`;
  if (entry.as === 'density') return `calc(var(--${role}) * var(--${entry.with}))`;
  throw new Error(`generate-token-tree: the role ${role} combines as ${entry.as}, which is not level, width or density.`);
}

function indexBody(index: string, base: string) {
  return TREE[index]!.map((child) => {
    const path = leafPath(index, child);
    const file = join(base, TREE_DIR, path);
    const text = readFileSync(file, 'utf8');
    const headline = HEADLINE.exec(text)?.[1]?.trim();
    if (!headline) throw new Error(`generate-token-tree: ${TREE_DIR}/${path} has no # headline for its index row.`);
    const sentence = when(`${TREE_DIR}/${path}`, base);
    if (!sentence) throw new Error(`generate-token-tree: ${TREE_DIR}/${path} has no sentence that starts "Read this", so its index row has nothing to say.`);
    const link = child.endsWith('index.md') ? child : `${child}.md`;
    return `- [${headline}](./${link}): ${sentence}`;
  }).join('\n');
}

export function stateRows(roles: Record<string, RoleToken>) {
  return Object.entries(STATE_SELECTORS).flatMap(([attribute, selector]) => {
    const named = Object.keys(roles).filter((name) => {
      const ext = roles[name]!.$extensions?.[ARENA_EXT] as Record<string, unknown> | undefined;
      return ext?.audience === 'markup' && Array.isArray(ext.state) && ext.state.includes(attribute);
    }).sort();
    return named.length ? [`| \`${attribute}\` | \`${selector}\` | ${named.map((name) => `\`--${name}\``).join(', ')} |`] : [];
  });
}

export function regionBodies(base = root) {
  const roles = readJson(join(base, ROLES)) as Record<string, RoleToken>;
  const plugin = readJson(join(base, DEFAULT_PLUGIN)) as PluginTokens;
  const bodies = new Map<string, string>();
  for (const index of Object.keys(TREE)) bodies.set(index, indexBody(index, base));

  const byLeaf = new Map<string, string[]>();
  const markupRows = new Map<string, string[]>();
  const utilities = roleUtilities(base);
  const partners = new Map<string, string[]>();
  for (const [name, token] of Object.entries(roles))
    for (const entry of token.$extensions?.[ARENA_EXT]?.combines ?? [])
      partners.set(entry.with, [...(partners.get(entry.with) ?? []), name]);
  for (const name of Object.keys(roles).sort()) {
    const token = roles[name]!;
    const meta = token.$extensions?.[ARENA_EXT] as (RoleMeta & Record<string, any>) | undefined;
    if (!meta) throw new Error(`generate-token-tree: the role ${name} declares no ${ARENA_EXT} extension.`);
    const leaf = roleLeaf(name, { audience: meta.audience!, task: meta.task! });
    if (!meta.question) throw new Error(`generate-token-tree: the role ${name} has no question in its ${ARENA_EXT} extension, so its row would have an empty cell.`);
    const question = cell(meta.question);
    const roleDefault = meta.default === undefined ? 'none' : `\`${cell(meta.default)}\``;
    const answer = defaultAnswer(name, plugin, roles);
    const answers = answer === undefined ? `silent, falls to ${roleDefault}`
      : answer.light === answer.dark ? `\`${cell(answer.dark)}\``
        : `light \`${cell(answer.light)}\`; dark \`${cell(answer.dark)}\``;
    const row = `| \`--${name}\` | ${question} | ${token.$type} | ${meta.userScale ?? 'none'} | ${roleDefault} | ${answers} |`;
    byLeaf.set(leaf, [...(byLeaf.get(leaf) ?? []), row]);
    if (meta.audience === 'markup') {
      const mark = markupLeaf(meta.task!);
      const own = utilities.get(name) ?? [];
      const forms = [...(meta.combines ?? []).map((entry: Combine) => `\`${combination(name, entry, own)}\``),
        ...[...new Set(partners.get(name) ?? [])].sort().map((partner) => `read with \`--${partner}\``)];
      markupRows.set(mark, [...(markupRows.get(mark) ?? []),
        `| \`--${name}\` | ${question} | ${own.length ? own.map((utility) => `\`${utility}\``).join(', ') : 'none'} | ${forms.length ? forms.join('; ') : 'none'} |`]);
    }
  }
  for (const [leaf, rows] of byLeaf) {
    const opening = leaf.startsWith('plugin/') ? COMPAT.markup : COMPAT.component;
    bodies.set(leaf, [opening, '',
      '| role | question | type | user scale | role default | `default` answers |', '| --- | --- | --- | --- | --- | --- |', ...rows].join('\n'));
  }
  for (const [leaf, rows] of markupRows)
    bodies.set(leaf, [COMPAT.markup, '', '| role | question | utility | combines with |', '| --- | --- | --- | --- |', ...rows].join('\n'));

  bodies.set('markup/states.md', [bodies.get('markup/states.md') ?? '', '', '| attribute | selector | roles |', '| --- | --- | --- |', ...stateRows(roles)].join('\n'));

  for (const path of GENERATED_PATHS) if (!bodies.has(path)) bodies.set(path, '');
  const z = (readJson(join(base, LAYERING)) as { z: Record<string, { $value?: number; $description?: string }> }).z;
  const steps = Object.entries(z).filter(([key, step]) => !key.startsWith('$') && typeof step.$value === 'number')
    .sort((a, b) => a[1].$value! - b[1].$value!);
  bodies.set('markup/layers.md', ['| custom property | what sits there |', '| --- | --- |',
    ...steps.map(([step, token]) => `| \`--z-${step}\` | ${cell(token.$description ?? '')} |`)].join('\n'));
  return bodies;
}

function place(text: string, body: string, path: string) {
  const lines = text.split('\n');
  const from = lines.findIndex((line) => line === TREE_OPEN);
  const to = from === -1 ? -1 : lines.indexOf(TREE_CLOSE, from);
  if (body === '' && from === -1) return text;
  if (from === -1 || to === -1)
    throw new Error(`generate-token-tree: ${TREE_DIR}/${path} has no marker pair to write into. A person places the markers, `
      + `${TREE_OPEN} and ${TREE_CLOSE}, because where a section sits is the page's decision and only what it says belongs to this script.`);
  if (body === '') {
    const before = lines.slice(0, from);
    while (before.length > 0 && before[before.length - 1] === '') before.pop();
    return [...before, ...lines.slice(to + 1)].join('\n').replace(/\n*$/, '\n');
  }
  return [...lines.slice(0, from), TREE_OPEN, '', body, '', TREE_CLOSE, ...lines.slice(to + 1)].join('\n');
}

export function renderTree(base = root) {
  const rendered = new Map<string, string>();
  for (const [path, body] of regionBodies(base))
    rendered.set(path, place(readFileSync(join(base, TREE_DIR, path), 'utf8'), body, path));
  return rendered;
}

export function writeTree(base = root) {
  const written: string[] = [];
  for (const [path, after] of renderTree(base)) {
    const file = join(base, TREE_DIR, path);
    if (readFileSync(file, 'utf8') === after) continue;
    writeFileSync(file, after);
    written.push(path);
  }
  return written;
}

export const node = {
  name: 'generate:token-tree',
  reads: [ROLES, LAYERING, THEME, DEFAULT_PLUGIN, `${TREE_DIR}/**/*.md`],
  writes: GENERATED_PATHS.map((path) => `${TREE_DIR}/${path}`),
  feeds: ['check:token-tree', 'check:routes', 'check:register', 'check:skills', 'check:community', 'check:mcp', 'check:site', 'check:support', 'check:consumer', 'build:site', 'build:mcp-package'],
};

function main() {
  const written = writeTree();
  for (const path of written) console.log(`generate-token-tree: wrote ${TREE_DIR}/${path}`);
  console.log(`generate-token-tree: ${GENERATED_PATHS.length} page(s) carry their generated region`);
}

