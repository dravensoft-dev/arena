/* GENERATED-region writer for the token tree under skills/design/references/tokens/. A page is
 * placed by a person and only its region is filled here: an index lists its children from their own
 * headline and `Read this` sentence, a plugin or components leaf tables the roles that land in it,
 * a markup leaf gives each markup role its question, utilities and combination, and the layers leaf
 * lists the z steps. A plugin or components row also shows what the default plugin answers in light and dark.
 * Every row is derived from contracts/design/, the default plugin and frameworks/tailwind/Theme.css,
 * so no page can disagree with the role file. The scales leaves are
 * written by generate:npm-pages, and this only lists them in their index. A page with no rows carries
 * no marker pair, and a pair left on one is removed. */

